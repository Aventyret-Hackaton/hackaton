export const BLOCK_TEXT_HEIGHT = 9;

// Calls plot for every lit pixel and returns the width of the text. Row 0 is the top row.
export const drawBlockText = (text: string, plot: (column: number, row: number) => void): number => {
  let left = 0;
  for (const character of text) {
    const glyph = GLYPHS[character];
    if (!glyph) {
      left += SPACE_WIDTH + GLYPH_GAP;
      continue;
    }
    glyph.forEach((line, row) => {
      Array.from(line).forEach((pixel, column) => {
        if (pixel === '#') plot(left + column, row);
      });
    });
    left += glyph[0].length + GLYPH_GAP;
  }
  return left - GLYPH_GAP;
};
