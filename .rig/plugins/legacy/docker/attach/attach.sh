#!/usr/bin/env bash
set -euo pipefail

# rig-legacy-attach — makes unmigrated akka-tools sites work behind the rig
# proxy without a single change in their repos. Runs only in legacy mode
# (`rig proxy-legacy`, the compose profile `legacy`).
#
# THE NETWORK. The rig proxy runs --providers.docker.network=rig: Traefik finds
# the container via docker.sock regardless of network but looks up the backend IP
# on the rig network. If the site is on `proxy`/`akka_network` there is no IP there,
# so 404/504. The solution is NOT to move the site to the rig network: the legacy
# compose files put ALL services on the same network, and compose gives each
# service an alias = the service name. Two such sites on rig give two `db`,
# and docker's resolver answers with both. `docker network connect` sets no
# such alias (only the container name, which is site-prefixed), so only the ingress
# containers are connected, afterwards. Traefik does not see that as a container
# event and keeps the old IP, hence the restart of rig-proxy.
#
# THE CERTS. The legacy sites declare their domains in the Traefik rule
#   traefik.http.routers.<name>.rule=Host(`cms.mysite.test`)
# and carry no rig.hosts label (that one belongs to rig-cert). Here certs are issued
# from the rule (the same source Traefik routes on) into share/sites/legacy/ and a
# separate dynamic config (legacy-certs.yaml), so rig-cert and this one never
# write to each other's files.

RIG_NETWORK="${RIG_NETWORK:-rig}"
export CAROOT="${CAROOT:-/cert}"
SITES_DIR="$CAROOT/share/sites/legacy"
DYNAMIC_FILE="${DYNAMIC_FILE:-/config/legacy-certs.yaml}"

log() { echo "🔌 rig-legacy: $*"; }

if [ ! -f "$CAROOT/rootCA.pem" ] || [ ! -f "$CAROOT/rootCA-key.pem" ]; then
  log "❌ no rootCA in $CAROOT — run 'rig proxy-cert' on the host first"
  exit 1
fi
mkdir -p "$SITES_DIR"

proxy_running() {
  [ "$(docker container inspect -f '{{.State.Running}}' rig-proxy 2>/dev/null)" = "true" ]
}

labels_of() {
  docker inspect -f '{{range $k, $v := .Config.Labels}}{{$k}}={{$v}}{{"\n"}}{{end}}' "$1" 2>/dev/null || true
}

# Ingress = declares a route: legacy via a router rule, rig via rig.hosts.
# Both count. A migrated site that lost the rig network is just as broken.
is_ingress() {
  printf '%s\n' "$1" | grep -qE '^(traefik\.http\.routers\..*\.rule|rig\.hosts)='
}

on_network() {
  docker inspect -f '{{range $k, $v := .NetworkSettings.Networks}}{{$k}} {{end}}' "$1" 2>/dev/null \
    | grep -qw "$RIG_NETWORK"
}

connectable() {
  case "$(docker inspect -f '{{.HostConfig.NetworkMode}}' "$1" 2>/dev/null)" in
    host | none) return 1 ;;
  esac
  return 0
}

# Domains from router rules. HostRegexp/HostSNI are skipped: mkcert wants names.
hosts_from_rules() {
  printf '%s\n' "$1" \
    | grep -E '^traefik\.http\.routers\..*\.rule=' \
    | grep -oE 'Host\(`[^`]+`\)' \
    | sed -e 's/^Host(`//' -e 's/`)$//' \
    | sort -u
}

slugify() {
  local d="${1#\*.}"
  echo "${d//[^a-zA-Z0-9.-]/_}"
}

# Issue/update the cert for a site. 0 if something was written.
ensure_cert() {
  local slug cert key domains_file wanted
  slug="$(slugify "$1")"
  cert="$SITES_DIR/$slug.pem"
  key="$SITES_DIR/$slug-key.pem"
  domains_file="$SITES_DIR/$slug.domains"
  wanted="$(printf '%s\n' "$@")"
  if [ -f "$cert" ] && [ -f "$key" ] && [ -f "$domains_file" ] \
     && [ "$wanted" = "$(cat "$domains_file")" ]; then
    return 1
  fi
  log "issuing cert for: $* → share/sites/legacy/$slug.pem"
  mkcert -cert-file "$cert" -key-file "$key" "$@" 2>/dev/null
  chmod 644 "$cert" "$key"
  printf '%s\n' "$wanted" > "$domains_file"
  return 0
}

write_dynamic_config() {
  local tmp="$DYNAMIC_FILE.tmp" count=0 f base
  {
    echo "# AUTOGENERATED by rig-legacy-attach — do not edit, do not commit"
    echo "tls:"
    echo "  certificates:"
    for f in "$SITES_DIR"/*.pem; do
      case "$f" in *-key.pem) continue ;; esac
      [ -e "$f" ] || continue
      base="${f##*/}"
      echo "    - certFile: /cert/share/sites/legacy/$base"
      echo "      keyFile: /cert/share/sites/legacy/${base%.pem}-key.pem"
      count=$((count + 1))
    done
  } > "$tmp"
  if [ "$count" -eq 0 ]; then
    rm -f "$tmp" "$DYNAMIC_FILE"
    return 0
  fi
  mv "$tmp" "$DYNAMIC_FILE"
  log "updated $DYNAMIC_FILE ($count legacy certs)"
}

# Cert for a container that declares domains in rules but lacks rig.hosts
# (rig sites are handled by rig-cert). 0 if a cert was written.
handle_certs() {
  local labels hosts
  labels="$(labels_of "$1")"
  [ -n "$labels" ] || return 1
  printf '%s\n' "$labels" | grep -q '^rig\.hosts=' && return 1
  hosts="$(hosts_from_rules "$labels")"
  [ -n "$hosts" ] || return 1
  # shellcheck disable=SC2086
  ensure_cert $hosts
}

# All running containers, not just the event's: a `compose up` starts
# www and cms within a second or so, and one sweep takes both in the same round
# (= one Traefik restart, not two). 0 if something was connected.
reconcile_network() {
  local cid n=0 labels
  for cid in $(docker ps -q); do
    labels="$(labels_of "$cid")"
    is_ingress "$labels" || continue
    on_network "$cid" && continue
    connectable "$cid" || continue
    if docker network connect "$RIG_NETWORK" "$cid" 2>/dev/null; then
      log "$(docker inspect -f '{{.Name}}' "$cid" | sed 's|^/||') → $RIG_NETWORK"
      n=$((n + 1))
    fi
  done
  [ "$n" -gt 0 ]
}

handle() {
  proxy_running || return 0
  local changed=0 cid
  for cid in $(docker ps -q); do
    if handle_certs "$cid"; then
      changed=1
    fi
  done
  [ "$changed" = 1 ] && write_dynamic_config
  if reconcile_network; then
    sleep 2
    reconcile_network || true
    docker restart rig-proxy >/dev/null 2>&1 \
      && log "restarted rig-proxy — rereads the backend IPs"
  fi
  return 0
}

log "reconciling running containers (network + certs from router rules)"
START="$(date +%s)"
write_dynamic_config
handle || true

log "listening to docker events"
docker events --since "$START" \
  --filter type=container --filter event=start \
  --format '{{.ID}}' |
while read -r _; do
  handle || true
done
